# 「このアプリの紹介」画面 - 主な機能・特徴・使い方の説明だけを表示する(入力はない)
#
# 文章は、実際に動いている機能と食い違わないよう、機能を変えたらここも見直すこと
# (試合形式の一覧は tennis_stats.MATCH_FORMATS から作るので、形式の追加・名前変更は自動で反映される)

from pathlib import Path

import pandas as pd
import streamlit as st

from tennis_stats import MATCH_FORMATS

ASSETS = Path(__file__).parent / "assets"

st.image(str(ASSETS / "logo_wide.svg"), width=320)
st.markdown("#### 仲間とのテニスを、組み合わせ決めから成績まで、スマホ1台で")
st.write(
    "てにろぐ君は、アマチュアのテニス仲間で集まったときのための記録アプリです。"
    "ダブルスの対戦の組み合わせを自動で決め、試合結果を入力すれば、"
    "一人ひとりの成績をその場で集計します。"
)

st.header("主な機能")

st.subheader("🎾 ダブルス対戦")
st.markdown(
    "- **組み合わせを自動で決定** — 集まったメンバー(4人以上)を登録すると、毎試合の"
    "ペアと対戦相手をアプリが決めます\n"
    "- **なるべく公平に** — 次の順番で優先して組み合わせます\n"
    "    1. 試合数の少ない人から出る(休みが偏らない)\n"
    "    2. 同じペアの繰り返しを避ける\n"
    "    3. 同じ対戦相手の繰り返しを避ける\n"
    "    4. まったく同じ対戦カードの繰り返しを避ける\n"
    "- **途中の出入りに対応** — 途中で帰る人は「以降の試合で外す」、遅れて来た人は"
    "「追加」。抜けた人の成績は消えず、遅れて来た人も他の人と同じペースで試合に入ります\n"
    "- **個人成績** — 勝・負・引分、得失セット、勝率、ゲーム獲得率を一覧表で表示"
)

st.subheader("📊 シングルス集計")
st.markdown(
    "- 対戦相手ごとに試合結果を登録し、勝率・ゲーム獲得率・対戦相手別の勝率グラフを表示\n"
    "- CSVファイルへの保存・読み込みに対応(過去の記録をまとめて取り込めます)"
)

st.subheader("📝 選べる試合形式")
st.write("最初に1回選べば、次の試合からも同じ形式で入力できます。途中で変えることもできます。")
FORMAT_NOTES = {
    "one_set": "6ゲーム先取(6-4、7-5、7-6 など)",
    "four_first": "4ゲーム先取。3-3の後はノーアドで4-3",
    "four_match": "合計4ゲーム。2-2は引分",
    "free": "決まりなし。3-1、3-3(引分)、10-7(10ポイントタイブレーク)なども可",
    "three_set": "6ゲーム先取のセットで、2セット先取",
}
st.dataframe(
    pd.DataFrame([
        {"形式": spec["label"], "内容": FORMAT_NOTES.get(key, "")}
        for key, spec in MATCH_FORMATS.items()
    ]),
    hide_index=True, width="stretch",
)

st.header("特徴")
st.markdown(
    "- **スマホで押しやすい** — スコアは数字を選ぶだけ。キーボードの切り替えは不要です\n"
    "- **ありえないスコアは登録しない** — 「6-5」のように試合形式に合わないスコアや、"
    "2-0で勝負がついた後の第3セットなどは、その場で知らせて登録しません\n"
    "- **入力の表記ゆれを補正** — CSVの全角数字「６－３」なども正しく読み取ります"
)

st.header("使い方(ダブルス)")
st.markdown(
    "1. メンバーの名前を登録して「対戦を開始する」\n"
    "2. 試合形式を選ぶ(初回だけ)\n"
    "3. 表示された組み合わせで試合をし、スコアを選んで「結果を登録して次の試合へ」\n"
    "4. 終わったら「ここで終了して成績を見る」"
)

st.info(
    "ご注意: ダブルスの対戦データは、アプリを開いている全員で共有されます(だれが登録しても"
    "数秒で全員の画面に出ます)。アプリが再起動すると消えることがあるので、ときどき"
    "「途中経過の保存・再開」で保存してください。"
    "シングルスの記録は自分のブラウザだけに残り、閉じると消えるので「CSVをダウンロード」で保存してください。"
)
